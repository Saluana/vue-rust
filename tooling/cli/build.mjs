// vue-native build (WP-APP1): compiles a project, writes its Rust crate, builds the crate for wasm32-unknown-unknown and
// packages the web output (hosts/web/ABI.md, "Build outputs"):
//   <out>/<lib>-<sha256 prefix 16>.wasm   the app: vn-renderer-dom's ABI exports, the app's vn_start, the runtime
//   <out>/vn-host.js                      the glue (hosts/web/vn-host.js, ABI 1), copied unchanged
//   <out>/index.html                      the page: creates the container, loads the glue, calls vn_start()
//   <out>/app-<sha256 prefix 16>.css      the project's <style> blocks (only when there are any)
//   <out>/manifest.json                   tool-owned: { tool: 'vue-native', files, ... }; reruns clean only these files
//   <out>/.vn-crate/                      the generated Rust crate (sources only)
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { moduleFileName, modulesTableRs } from '../../compiler/project/table.mjs';
import { asyncRuntimeRs } from '../harness/build.mjs';
import { FRAMEWORK_ROOT, UsageError, compileAt, diagnosticJson, formatDiagnostics, resolveProject } from './project.mjs';

export const TOOL = 'vue-native';
export const TOOL_VERSION = '0.0.1';
export const WASM_TARGET = 'wasm32-unknown-unknown';
export const ABI_VERSION = 1;
// Exports every web app must have (hosts/web/ABI.md, plus the app entry vn_start). vn-host.js refuses a module without them.
export const ABI_EXPORTS = ['memory', 'vn_abi_version', 'vn_init', 'vn_alloc', 'vn_free', 'vn_event', 'vn_timer', 'vn_start'];
const ABI_IMPORT_MODULE = 'vn_host';
const CONTAINER_RE = /^#[A-Za-z][A-Za-z0-9_-]*$/;
const NAME_RE = /^[a-z][a-z0-9-]*$/;
// Natives the web target provides (the runtime's "vue" module); anything else is refused at build time.
const WEB_NATIVES = new Set(['vue']);
const here = path.dirname(fileURLToPath(import.meta.url));
const HEADLESS_MAIN = path.join(here, 'headless', 'main.rs');

// A build that cannot finish: the message is printed as is (exit status 1).
export class BuildError extends Error {
  constructor(message) {
    super(message);
    this.name = 'BuildError';
  }
}

// The environment for cargo: the project-local toolchain (toolchain/, see scripts/env.sh) when it is present, and a
// private target directory unless CARGO_TARGET_DIR says otherwise.
export function toolEnv(base = process.env) {
  const env = { ...base, CARGO_INCREMENTAL: '0' };
  const cargoHome = path.join(FRAMEWORK_ROOT, 'toolchain', 'cargo');
  if (fs.existsSync(path.join(cargoHome, 'bin'))) {
    env.CARGO_HOME = cargoHome;
    env.RUSTUP_HOME = path.join(FRAMEWORK_ROOT, 'toolchain', 'rustup');
    env.PATH = `${cargoHome}/bin:${env.PATH ?? ''}`;
  }
  env.CARGO_TARGET_DIR ??= path.join(FRAMEWORK_ROOT, 'target', 'vue-native');
  return env;
}

function sha256(data) {
  return crypto.createHash('sha256').update(data).digest('hex');
}

function writeFile(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

// Crate and library names from an app name: counter -> vn-app-counter / vn_app_counter.
export function crateNames(name) {
  if (!NAME_RE.test(name)) {
    throw new UsageError(`app name "${name}" must start with a lowercase letter and use only a-z, 0-9 and "-"`);
  }
  return { pkg: `vn-app-${name}`, lib: `vn_app_${name.replace(/-/g, '_')}` };
}

// The default app name for a project directory: its base name, lowercased, with other characters turned into "-".
export function defaultName(root) {
  const slug = path.basename(root).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').replace(/^[^a-z]+/, '');
  return slug === '' ? 'app' : slug;
}

// The Cargo manifest of a generated crate. Path dependencies name the framework crates of this checkout. The empty
// [workspace] table keeps the generated crate out of the framework workspace.
export function cargoToml({ pkg, lib }) {
  const dep = (crate) => `{ path = ${JSON.stringify(path.join(FRAMEWORK_ROOT, 'crates', crate))} }`;
  return [
    '# Generated by vue-native build (WP-APP1). Tool-owned: do not edit.',
    '[package]', `name = "${pkg}"`, 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[lib]', `name = "${lib}"`, 'crate-type = ["cdylib"]', '',
    '[dependencies]',
    `vn-value = ${dep('value')}`,
    `vn-runtime = ${dep('runtime')}`,
    `vn-renderer-dom = ${dep('renderer-dom')}`,
    '', '[workspace]', '',
  ].join('\n');
}

// src/project/natives.rs: registers the natives the project imports. Only the web natives exist.
export function nativesRs(natives) {
  const lines = [
    '// Generated by vue-native build (WP-APP1) from the project natives. Tool-owned: do not edit.',
    'use vn_value::Rt;',
    '',
    'pub fn register(rt: &Rt) {',
    '    let _ = rt;',
  ];
  for (const name of natives) {
    if (!WEB_NATIVES.has(name)) throw new BuildError(`the project imports native module "${name}", which web apps do not provide`);
    if (name === 'vue') lines.push('    let _ = vn_runtime::exports::register_vue_module(rt);');
  }
  lines.push('}', '');
  return lines.join('\n');
}

// The files of src/project/ for a compiled project (the layout of tooling/harness/run-projects.mjs): mod.rs, natives.rs,
// modules.rs and one m<k>.rs per compiled module. Keys are paths under src/.
export function projectFiles(result) {
  const compiled = result.modules.filter((m) => m.rust !== null);
  const files = {
    'project/mod.rs': [
      '// Generated by vue-native build (WP-APP1). Tool-owned: do not edit.',
      'pub mod natives;', 'pub mod modules;', ...compiled.map((_, k) => `pub mod ${moduleFileName(k)};`), '',
    ].join('\n'),
    'project/natives.rs': nativesRs(result.natives),
    'project/modules.rs': modulesTableRs(compiled, result.entryId),
  };
  compiled.forEach((m, k) => {
    files[`project/${moduleFileName(k)}.rs`] = m.rust;
  });
  return files;
}

// Serialises the cargo builds that share a target directory. Two builds of one app name write one wasm file, so the
// file must be read before another build replaces it. A lock directory is created atomically; a lock older than ten
// minutes is treated as left behind by a crashed build.
const LOCK_STALE_MS = 10 * 60 * 1000;
const LOCK_GIVE_UP_MS = 15 * 60 * 1000;
const SLEEP_CELL = new Int32Array(new SharedArrayBuffer(4));

export function withTargetLock(targetDir, fn) {
  fs.mkdirSync(targetDir, { recursive: true });
  const lock = path.join(targetDir, '.vue-native-build.lock');
  const started = Date.now();
  for (;;) {
    try {
      fs.mkdirSync(lock);
      break;
    } catch (err) {
      if (err.code !== 'EEXIST') throw err;
      try {
        if (Date.now() - fs.statSync(lock).mtimeMs > LOCK_STALE_MS) fs.rmdirSync(lock);
      } catch {
        // the other build has just finished and removed the lock
      }
      if (Date.now() - started > LOCK_GIVE_UP_MS) throw new BuildError(`timed out waiting for another build in ${targetDir}`);
      Atomics.wait(SLEEP_CELL, 0, 0, 200);
    }
  }
  try {
    return fn();
  } finally {
    fs.rmSync(lock, { recursive: true, force: true });
  }
}

// cargo build --release of a generated crate (args select the target); returns the bytes of its artifact.
function cargoBuild({ env, crateDir, pkg, args, artifact }) {
  const built = spawnSync('cargo', ['build', '--release', ...args, '--manifest-path', path.join(crateDir, 'Cargo.toml')], {
    env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, timeout: 900000,
  });
  if (built.error) throw new BuildError(`cannot run cargo: ${built.error.message}`);
  if (built.status !== 0) {
    const log = `${built.stderr ?? ''}${built.stdout ?? ''}`.trim().split('\n').slice(-60).join('\n');
    throw new BuildError(`cargo build failed for ${pkg}:\n${log}`);
  }
  return fs.readFileSync(artifact);
}
// src/vn_config.rs: the container selector the app mounts into (also "container" in manifest.json).
export function configRs(container) {
  return [
    '// Generated by vue-native build (WP-APP1) from the build options. Tool-owned: do not edit.',
    '/// The container selector that the app mounts into.',
    `pub const CONTAINER: &str = ${JSON.stringify(container)};`,
    '',
  ].join('\n');
}

// The Cargo manifest of a headless app: a native binary (src/main.rs) that runs an interaction script in a DocHost.
export function cargoTomlHeadless({ pkg }) {
  const dep = (crate) => `{ path = ${JSON.stringify(path.join(FRAMEWORK_ROOT, 'crates', crate))} }`;
  return [
    '# Generated by vue-native build (WP-APP1). Tool-owned: do not edit.',
    '[package]', `name = "${pkg}"`, 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[[bin]]', `name = "${pkg}"`, 'path = "src/main.rs"', '',
    '[dependencies]',
    `vn-value = ${dep('value')}`,
    `vn-runtime = ${dep('runtime')}`,
    `vn-dom = ${dep('dom')}`,
    `vn-testkit = ${dep('testkit')}`,
    '', '[workspace]', '',
  ].join('\n');
}

// Throws unless the module is a web app: every ABI export, and imports only from vn_host.
export function checkWebWasm(bytes) {
  let module;
  try {
    module = new WebAssembly.Module(bytes);
  } catch (err) {
    throw new BuildError(`the built wasm is not a valid module: ${err.message}`);
  }
  const exported = new Set(WebAssembly.Module.exports(module).map((e) => e.name));
  const missing = ABI_EXPORTS.filter((name) => !exported.has(name));
  if (missing.length > 0) throw new BuildError(`the built wasm lacks ABI exports: ${missing.join(', ')}`);
  const imports = WebAssembly.Module.imports(module);
  const foreign = [...new Set(imports.filter((i) => i.module !== ABI_IMPORT_MODULE).map((i) => `${i.module}.${i.name}`))];
  if (foreign.length > 0) throw new BuildError(`the built wasm imports outside ${ABI_IMPORT_MODULE}: ${foreign.join(', ')}`);
  return { exports: [...exported].sort(), imports: imports.length };
}

// The page shell. The container element is created here; vn_start() mounts into the selector the crate was built with.
export function pageShell({ title, container, css }) {
  const id = container.slice(1);
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${title.replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`)}</title>`,
    ...(css ? [`<link rel="stylesheet" href="${css}">`] : []),
    '</head>',
    '<body>',
    `<div id="${id}"></div>`,
    '<script type="module">',
    '// Loads the app named by manifest.json and starts it (hosts/web/ABI.md). window.vnReady resolves once it has started.',
    "import { createHost } from './vn-host.js';",
    'window.vnReady = (async () => {',
    "  const manifest = await fetch('./manifest.json').then((response) => response.json());",
    '  const host = await createHost({ document, wasmBytesOrUrl: new URL(manifest.wasm, location.href) });',
    '  window.vnHost = host;',
    '  host.exports.vn_start();',
    '  return host;',
    '})();',
    '</script>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
}

// Reads the manifest of a directory vue-native wrote earlier; null when the directory is not tool-owned.
function ownedManifest(dir) {
  try {
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
    // Build artifacts are flat filenames. Validate every entry before deleting any of them.
    const safe = file => typeof file === 'string' && file.length > 0
      && file !== '.' && file !== '..' && file !== '.vn-crate'
      && !file.includes('/') && !file.includes('\\') && !file.includes('\0')
      && !path.isAbsolute(file);
    return manifest.tool === TOOL && Array.isArray(manifest.files) && manifest.files.every(safe) ? manifest : null;
  } catch {
    return null;
  }
}

// Refuses an output directory that vue-native did not write. Runs before anything is compiled or written.
export function checkOutDir(out) {
  const dir = path.resolve(out);
  if (fs.existsSync(dir) && ownedManifest(dir) === null) {
    throw new BuildError(`refusing to write into ${out}: the directory exists and was not written by vue-native build`);
  }
}

// Prepares the output directory: a new one, or a directory vue-native wrote before (its files are removed first).
function prepareOutDir(out) {
  const dir = path.resolve(out);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
    return { dir, created: true };
  }
  checkOutDir(out);
  const previous = ownedManifest(dir);
  // The manifest stays until the new build succeeds, so a failed rerun leaves a directory that reruns still accept.
  for (const file of previous.files) {
    if (file !== 'manifest.json') fs.rmSync(path.join(dir, file), { force: true });
  }
  fs.rmSync(path.join(dir, '.vn-crate'), { recursive: true, force: true });
  return { dir, created: false };
}

// Builds one web app from Rust sources and packages it. libRs is the crate's src/lib.rs (it must define vn_start).
// projectFiles: { 'project/<file>': text } written under src/. meta: recorded in manifest.json.
export function buildWebApp({ out, name, libRs, projectFiles = {}, container = '#app', title = name, css = '', natives = [], meta = {} }) {
  if (!CONTAINER_RE.test(container)) throw new BuildError(`container "${container}" must be an id selector such as "#app"`);
  const base = crateNames(name);
  const { dir, created } = prepareOutDir(out);
  // Cargo keys the artifacts of a path package by its name and version, relative to its own workspace root, so two
  // generated crates with one name would share them. The suffix comes from the output directory: one crate per directory.
  const suffix = sha256(dir).slice(0, 8);
  const pkg = `${base.pkg}-${suffix}`;
  const lib = `${base.lib}_${suffix}`;
  const crateDir = path.join(dir, '.vn-crate');
  try {
    writeFile(path.join(crateDir, 'Cargo.toml'), cargoToml({ pkg, lib }));
    writeFile(path.join(crateDir, 'src', 'lib.rs'), libRs);
    writeFile(path.join(crateDir, 'src', 'vn_async.rs'), asyncRuntimeRs());
    writeFile(path.join(crateDir, 'src', 'vn_config.rs'), configRs(container));
    for (const [file, text] of Object.entries(projectFiles)) writeFile(path.join(crateDir, 'src', file), text);

    const env = toolEnv();
    const targetDir = path.resolve(env.CARGO_TARGET_DIR);
    const artifact = path.join(targetDir, WASM_TARGET, 'release', `${lib}.wasm`);
    const bytes = withTargetLock(targetDir, () => cargoBuild({ env, crateDir, pkg, args: ['--target', WASM_TARGET], artifact }));
    const abi = checkWebWasm(bytes);
    const hash = sha256(bytes);
    const wasm = `${base.lib}-${hash.slice(0, 16)}.wasm`;
    fs.writeFileSync(path.join(dir, wasm), bytes);
    fs.copyFileSync(path.join(FRAMEWORK_ROOT, 'hosts', 'web', 'vn-host.js'), path.join(dir, 'vn-host.js'));
    let cssFile = null;
    if (css.trim() !== '') {
      cssFile = `app-${sha256(css).slice(0, 16)}.css`;
      fs.writeFileSync(path.join(dir, cssFile), css.endsWith('\n') ? css : `${css}\n`);
    }
    fs.writeFileSync(path.join(dir, 'index.html'), pageShell({ title, container, css: cssFile }));
    const files = [wasm, 'vn-host.js', 'index.html', ...(cssFile ? [cssFile] : []), 'manifest.json'];
    const manifest = {
      tool: TOOL,
      toolVersion: TOOL_VERSION,
      target: 'web',
      name,
      crate: pkg,
      title,
      abiVersion: ABI_VERSION,
      wasm,
      hash,
      bytes: bytes.length,
      gzipBytes: zlib.gzipSync(bytes, { level: 9 }).length,
      glue: 'vn-host.js',
      container,
      css: cssFile,
      natives,
      profile: 'release',
      wasmExports: abi.exports,
      wasmImports: abi.imports,
      ...meta,
      files,
    };
    fs.writeFileSync(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    return { dir, manifest };
  } catch (err) {
    if (created) fs.rmSync(dir, { recursive: true, force: true });
    throw err;
  }
}

// The lib.rs of a project's web app: the vue native module, the project's modules, and vn_start mounting the root
// component into the container. Not written yet: the runtime renderer is bound to the in-memory DocHost (DomCtx::new takes
// &DocHost, crates/runtime/src/dom_events.rs), so WebHost cannot be installed as the renderer's host.
function projectLibRs() {
  throw new BuildError('web builds of .vue projects are not available yet: the runtime renderer runs only on the in-memory DocHost (DomCtx::new takes a DocHost), so WebHost cannot be installed. Use --target headless to run an app.');
}

// Compiles a project for a target; throws BuildError with the error diagnostics when it fails.
function compileOrThrow({ root, entry, target }) {
  const compiled = compileAt({ root, entry, target });
  if (!compiled.ok) {
    const errors = compiled.diagnostics.filter((d) => d.severity === 'error');
    throw new BuildError(`${formatDiagnostics(errors, compiled.sourceOf)}\n\n${errors.length} error(s): nothing was built`);
  }
  return compiled;
}

// Compiles a project and builds it for the web target. Returns { dir, manifest }; throws BuildError with the diagnostics.
export function buildProjectWeb({ root, entry, out, name, container = '#app' }) {
  const compiled = compileOrThrow({ root, entry, target: 'web' });
  const modules = compiled.modules.filter((m) => m.rust !== null);
  const css = compiled.modules.flatMap((m) => m.styles.map((s) => s.code)).join('\n');
  return buildWebApp({
    out,
    name,
    libRs: projectLibRs(),
    projectFiles: projectFiles(compiled),
    container,
    css,
    natives: compiled.natives,
    meta: { entry: compiled.entryId, modules: modules.map((m) => m.id), diagnostics: compiled.diagnostics.map(diagnosticJson) },
  });
}

// Compiles a project into a headless app: a native binary that runs an interaction script (headless/main.rs).
export function buildHeadlessApp({ root, entry, out, name }) {
  const compiled = compileOrThrow({ root, entry, target: 'native' });
  const base = crateNames(name);
  const { dir, created } = prepareOutDir(out);
  const suffix = sha256(dir).slice(0, 8);
  const pkg = `${base.pkg}-${suffix}`;
  const crateDir = path.join(dir, '.vn-crate');
  try {
    writeFile(path.join(crateDir, 'Cargo.toml'), cargoTomlHeadless({ pkg }));
    writeFile(path.join(crateDir, 'src', 'main.rs'), fs.readFileSync(HEADLESS_MAIN, 'utf8'));
    writeFile(path.join(crateDir, 'src', 'vn_async.rs'), asyncRuntimeRs());
    writeFile(path.join(crateDir, 'src', 'vn_config.rs'), configRs('#app'));
    for (const [file, text] of Object.entries(projectFiles(compiled))) writeFile(path.join(crateDir, 'src', file), text);
    const env = toolEnv();
    const targetDir = path.resolve(env.CARGO_TARGET_DIR);
    const artifact = path.join(targetDir, 'release', pkg);
    const bytes = withTargetLock(targetDir, () => cargoBuild({ env, crateDir, pkg, args: [], artifact }));
    fs.writeFileSync(path.join(dir, name), bytes, { mode: 0o755 });
    const files = [name, 'manifest.json'];
    const manifest = {
      tool: TOOL,
      toolVersion: TOOL_VERSION,
      target: 'headless',
      name,
      crate: pkg,
      binary: name,
      bytes: bytes.length,
      natives: compiled.natives,
      entry: compiled.entryId,
      modules: compiled.modules.filter((m) => m.rust !== null).map((m) => m.id),
      diagnostics: compiled.diagnostics.map(diagnosticJson),
      files,
    };
    fs.writeFileSync(path.join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    return { dir, manifest };
  } catch (err) {
    if (created) fs.rmSync(dir, { recursive: true, force: true });
    throw err;
  }
}

// vue-native build <entry.vue|dir> --target web|headless --out <new-dir> [--root <dir>] [--name <name>]
export function build(positionals, values, io) {
  if (positionals.length !== 1) throw new UsageError('build takes one entry .vue file or project directory');
  if (values.target === undefined) throw new UsageError('build needs --target web (or headless)');
  if (values.target !== 'web' && values.target !== 'headless') {
    throw new UsageError(`unknown build target "${values.target}" (web or headless)`);
  }
  if (values.out === undefined) throw new UsageError('build needs --out <new-dir>');
  checkOutDir(values.out);
  const { root, entry } = resolveProject(positionals[0], { root: values.root });
  const name = values.name ?? defaultName(root);
  if (values.target === 'headless') {
    const result = buildHeadlessApp({ root, entry, out: values.out, name });
    io.out.write(`built ${result.manifest.name} for headless: ${result.manifest.binary} ${result.manifest.bytes} bytes in ${result.dir}\n`);
    return 0;
  }
  const result = buildProjectWeb({ root, entry, out: values.out, name });
  const m = result.manifest;
  io.out.write(`built ${m.name} for web: ${m.wasm} ${m.bytes} bytes (gzip ${m.gzipBytes}) in ${result.dir}\n`);
  return 0;
}
