#!/usr/bin/env node
// SFC fixture lowering check (WP-C1c, item 4): every tests/sfc/fixtures/ok-*.vue is compiled as a project (compileProject,
// the whole fixture directory as the file map, external src read from the fixture directory), then the generated Rust of
// all lowered fixtures is written as one crate (target/scenarios/sfc-check) and checked with `cargo check`.
//   node tooling/harness/check-sfc-lowering.mjs [--fixtures tests/sfc/fixtures]
// Output: the lowering count, the cargo check result, and the fixtures whose generated Rust does not check.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { compileProject } from '../../compiler/project/index.mjs';
import { modulesTableRs, moduleFileName } from '../../compiler/project/table.mjs';
import { ROOT, cargoEnv, writeAsyncRuntime } from './build.mjs';

const args = process.argv.slice(2);
const fixturesDir = path.resolve(ROOT, args[args.indexOf('--fixtures') + 1] || 'tests/sfc/fixtures');
const CRATE = path.join(ROOT, 'target', 'scenarios', 'sfc-check');

function writeIfChanged(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  writeFileSync(file, text);
}

const names = readdirSync(fixturesDir).filter((f) => f.startsWith('ok-') && f.endsWith('.vue')).sort();
const files = Object.fromEntries(names.map((n) => [n, readFileSync(path.join(fixturesDir, n), 'utf8')]));
const lowered = [];
const failed = [];
let tsCount = 0;
for (const n of names) {
  const r = compileProject({ entry: n, files, sfcRootDir: fixturesDir });
  if (!r.ok) {
    const d = r.diagnostics.find((x) => x.severity === 'error');
    failed.push(`${n}: ${d ? `${d.code} ${d.message}` : 'not lowered'}`);
    continue;
  }
  const compiled = r.modules.filter((m) => m.rust !== null);
  if (compiled.some((m) => m.codeLang === 'ts')) tsCount += 1;
  lowered.push({ name: n, entryId: r.entryId, compiled });
}

// One crate: fixture j is src/f<j>/ (mod.rs, modules.rs, m<k>.rs); main.rs declares the fixtures.
writeIfChanged(path.join(CRATE, 'Cargo.toml'), [
  '# Generated by tooling/harness/check-sfc-lowering.mjs (WP-C1c). Do not edit.',
  '[package]', 'name = "vn-sfc-check"', 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
  '[dependencies]', `vn-value = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'value'))} }`, '',
  '[workspace]', '',
].join('\n'));
lowered.forEach((f, j) => {
  const dir = path.join(CRATE, 'src', `f${j}`);
  writeIfChanged(path.join(dir, 'mod.rs'), ['pub mod modules;', ...f.compiled.map((_, k) => `pub mod ${moduleFileName(k)};`), ''].join('\n'));
  writeIfChanged(path.join(dir, 'modules.rs'), modulesTableRs(f.compiled, f.entryId));
  f.compiled.forEach((m, k) => writeIfChanged(path.join(dir, `${moduleFileName(k)}.rs`), m.rust));
});
writeAsyncRuntime(path.join(CRATE, 'src'));
writeIfChanged(path.join(CRATE, 'src', 'main.rs'), [
  '// Generated by tooling/harness/check-sfc-lowering.mjs (WP-C1c). Do not edit.',
  'mod vn_async;',
  ...lowered.map((_, j) => `mod f${j};`), '', 'fn main() {}', '',
].join('\n'));

const check = spawnSync('cargo', ['check', '--quiet', '--message-format=short', '--manifest-path', path.join(CRATE, 'Cargo.toml')], {
  env: cargoEnv(), encoding: 'utf8', timeout: 580000,
});
const output = `${check.stdout ?? ''}${check.stderr ?? ''}`;
const badFixtures = new Set();
for (const line of output.split('\n')) {
  const m = /^src\/f(\d+)\/[^:]*:\d+:\d+: error/.exec(line);
  if (m) badFixtures.add(Number(m[1]));
}
const checkFailures = [...badFixtures].sort((a, b) => a - b).map((j) => lowered[j].name);

console.log(`fixtures ${names.length}: lowered ${lowered.length}, not lowered ${failed.length}; TypeScript fixtures lowered ${tsCount}`);
for (const f of failed) console.log(`  not lowered: ${f}`);
console.log(`cargo check: ${check.status === 0 ? 'ok' : 'FAILED'} (${lowered.length} fixture projects; ${checkFailures.length} with errors)`);
for (const n of checkFailures) console.log(`  does not check: ${n}`);
if (check.status !== 0 && checkFailures.length === 0) console.log(output.split('\n').filter((l) => /error/.test(l)).slice(0, 5).join('\n'));
process.exitCode = failed.length === 0 && check.status === 0 ? 0 : 1;
