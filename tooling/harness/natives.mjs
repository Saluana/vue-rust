import { f64Lit } from '../../compiler/emit/names.mjs';

// Test native modules (WP-C1c). A project's native.json maps a native specifier to its exports:
//   { "vue": { "identity": "identity", "answer": { "number": 42 } } }
// A string names an implementation from IMPLS (the same behaviour in JavaScript for the Node oracle and in Rust for the
// generated crate); { "number" | "string" | "bool": v } is a constant export. Nothing else is accepted.
export const IMPLS = Object.freeze({
  identity: { length: 1, js: '(...args) => args[0]', rust: 'Ok(call.arg(0))' },
  pair: {
    length: 2, js: '(a, b) => [a, b]',
    rust: 'Ok(Value::Object(rt.new_array(vec![call.arg(0), call.arg(1)])))',
  },
  box: {
    length: 1, js: '(a) => ({ value: a })',
    rust: 'let o = rt.new_object(); rt.define_data(o, PropKey::from_str("value"), call.arg(0), Flags::ALL)?; Ok(Value::Object(o))',
  },
  throws: { length: 1, js: '(a) => { throw a; }', rust: 'Err(Throw(call.arg(0)))' },
});

// Validates a native.json object; returns the list of { specifier, name, kind, impl|value } entries.
export function nativeEntries(spec) {
  if (spec === null || typeof spec !== 'object' || Array.isArray(spec)) throw new TypeError('native.json must be an object');
  const out = [];
  for (const [specifier, exportsObj] of Object.entries(spec)) {
    if (exportsObj === null || typeof exportsObj !== 'object') throw new TypeError(`native.json: ${specifier} must map export names`);
    for (const [name, def] of Object.entries(exportsObj)) {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new TypeError(`native.json: export name ${name} is not an identifier`);
      if (typeof def === 'string') {
        if (!Object.hasOwn(IMPLS, def)) throw new TypeError(`native.json: unknown implementation ${def}`);
        out.push({ specifier, name, kind: 'fn', impl: def });
      } else if (def && typeof def === 'object') {
        const keys = Object.keys(def);
        if (keys.length !== 1 || !['number', 'string', 'bool'].includes(keys[0])) throw new TypeError(`native.json: bad constant for ${name}`);
        out.push({ specifier, name, kind: keys[0], value: def[keys[0]] });
      } else {
        throw new TypeError(`native.json: bad export ${name}`);
      }
    }
  }
  return out;
}

// JavaScript source of one native module (for the Node loader hook).
export function nativeModuleJs(specifier, entries) {
  const lines = [];
  for (const e of entries.filter((x) => x.specifier === specifier)) {
    if (e.kind === 'fn') lines.push(`export const ${e.name} = ${IMPLS[e.impl].js};`);
    else if (e.kind === 'string') lines.push(`export const ${e.name} = ${JSON.stringify(e.value)};`);
    else lines.push(`export const ${e.name} = ${e.kind === 'number' ? (Object.is(e.value, -0) ? '-0' : String(e.value)) : String(e.value === true)};`);
  }
  return `${lines.join('\n')}\n`;
}

// Rust source of the native registration for one project (module natives.rs). Specifiers are registered with their
// exports; implementations are plain functions with the CodeFn signature.
export function nativeRustRs(entries) {
  const specs = [...new Set(entries.map((e) => e.specifier))];
  const fns = [...new Set(entries.filter((e) => e.kind === 'fn').map((e) => e.impl))];
  const lines = [
    '// Generated by tooling/harness/run-projects.mjs (WP-C1c) from native.json. Do not edit.',
    'use vn_value::*;',
    '',
  ];
  for (const f of fns) {
    lines.push(`fn nat_${f}(rt: &Rt, call: &Call<'_>) -> Res<Value> {`, `    let _ = rt;`, `    ${IMPLS[f].rust}`, '}', '');
  }
  lines.push('pub fn register(rt: &Rt) {');
  for (const spec of specs) {
    const list = entries.filter((e) => e.specifier === spec).map((e) => {
      if (e.kind === 'fn') {
        return `(${JSON.stringify(e.name)}, Value::Object(rt.new_function(nat_${e.impl}, FnInfo::new(${JSON.stringify(e.name)}, ${IMPLS[e.impl].length}, FnKind::Normal), &[])))`;
      }
      if (e.kind === 'string') return `(${JSON.stringify(e.name)}, Value::String(JsStr::from_str(${JSON.stringify(e.value)})))`;
      if (e.kind === 'bool') return `(${JSON.stringify(e.name)}, Value::Bool(${e.value === true ? 'true' : 'false'}))`;
      return `(${JSON.stringify(e.name)}, Value::Number(${f64Lit(Object.is(e.value, -0) ? '-0' : String(e.value))}))`;
    });
    lines.push(`    rt.register_native_module(${JSON.stringify(spec)}, vec![`, ...list.map((x) => `        ${x},`), '    ]);');
  }
  lines.push('}', '');
  return lines.join('\n');
}
