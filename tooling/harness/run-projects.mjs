#!/usr/bin/env node
// Project runs (WP-C1c). Each directory under tests/language/projects that holds scenario.js is one project: its files
// are compiled as one module graph (compileProject, entry scenario.js), native imports come from native.json, and the
// generated crate target/scenarios/projects runs the project's `run` export. The expected document is the Node oracle's
// run of the same files (ESM, native specifiers answered by natives-hooks.mjs), stored as expected.json in the project.
//   node tooling/harness/run-projects.mjs [--dir tests/language/projects] [--filter text] [--write-expected]
// A project that has no expected.json fails. Projects with a .vue file cannot run in the Node oracle: their expected.json
// is written by hand (--write-expected skips them).
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileProject } from '../../compiler/project/index.mjs';
import { modulesTableRs, moduleFileName } from '../../compiler/project/table.mjs';
import { compareDocs, describeDiff } from '../oracle/compare.mjs';
import { nativeEntries, nativeRustRs } from './natives.mjs';
import { ROOT, TARGET_DIR, cargoEnv, writeAsyncRuntime } from './build.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : dflt;
};
const flag = (name) => args.includes(name);
const dirArg = path.resolve(ROOT, opt('--dir', 'tests/language/projects'));
const filter = opt('--filter', '');
const CRATE = path.join(ROOT, 'target', 'scenarios', 'projects');
const BIN = path.join(TARGET_DIR, 'debug', 'vn-projects');

function writeIfChanged(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  writeFileSync(file, text);
}

// Every project file below dir (not native.json or expected.json), keyed by its path under the project root.
function readProject(dir) {
  const files = {};
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(js|mjs|ts|vue)$/.test(e.name)) files[path.relative(dir, p).split(path.sep).join('/')] = readFileSync(p, 'utf8');
    }
  };
  walk(dir);
  return files;
}

function nativesOf(dir) {
  const f = path.join(dir, 'native.json');
  return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : {};
}

function listProjects(root) {
  return readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(path.join(root, e.name, 'scenario.js')))
    .map((e) => e.name)
    .sort()
    .filter((name) => name.includes(filter));
}

// Rust crate: one directory per project (mod.rs, natives.rs, modules.rs, m<k>.rs), main.rs with the scenario table.
function writeCrate(projects) {
  writeIfChanged(path.join(CRATE, 'Cargo.toml'), [
    '# Generated by tooling/harness/run-projects.mjs (WP-C1c). Do not edit.',
    '[package]', 'name = "vn-projects"', 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[dependencies]',
    `vn-value = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'value'))} }`,
    `vn-testkit = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'testkit'))} }`, '',
    '[workspace]', '',
  ].join('\n'));
  writeAsyncRuntime(path.join(CRATE, 'src'));
  const mains = ['mod vn_async;'];
  const entries = [];
  projects.forEach((p, j) => {
    const dir = path.join(CRATE, 'src', `p${j}`);
    const mods = p.compiled.map((_, k) => `pub mod ${moduleFileName(k)};`);
    writeIfChanged(path.join(dir, 'mod.rs'), [
      '// Generated by tooling/harness/run-projects.mjs (WP-C1c). Do not edit.',
      'pub mod natives;', 'pub mod modules;', ...mods, '',
    ].join('\n'));
    writeIfChanged(path.join(dir, 'natives.rs'), nativeRustRs(p.natives));
    writeIfChanged(path.join(dir, 'modules.rs'), modulesTableRs(p.compiled, p.entryId));
    p.compiled.forEach((m, k) => writeIfChanged(path.join(dir, `${moduleFileName(k)}.rs`), m.rust));
    mains.push(`mod p${j};`);
    entries.push([
      `fn entry${j}(rt: &Rt) -> Res<ScenarioEntry> {`,
      `    p${j}::natives::register(rt);`,
      `    for d in p${j}::modules::defs() {`,
      '        rt.register_module_def(d);',
      '    }',
      `    let m = rt.load_module(p${j}::modules::entry())?;`,
      '    let run = match rt.module_export_cell(m, "run")? {',
      '        Some(c) => rt.cell_get(c),',
      '        None => Value::Undefined,',
      '    };',
      '    Ok(ScenarioEntry { run })',
      '}',
    ].join('\n'));
  });
  const table = projects.map((p, j) => `    (${JSON.stringify(p.name)}, entry${j} as ScenarioFn),`);
  writeIfChanged(path.join(CRATE, 'src', 'main.rs'), [
    '// Generated by tooling/harness/run-projects.mjs (WP-C1c). Do not edit.',
    'use vn_testkit::{scenario_main, ScenarioEntry, ScenarioFn};',
    'use vn_value::{Res, Rt, Value};',
    ...mains, '', ...entries, '',
    'fn main() {', '    scenario_main(&[', ...table, '    ]);', '}', '',
  ].join('\n'));
}

function build() {
  const r = spawnSync('cargo', ['build', '--quiet', '--manifest-path', path.join(CRATE, 'Cargo.toml')], {
    env: cargoEnv(), encoding: 'utf8', timeout: 580000,
  });
  return { ok: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim() };
}

function runRust(name) {
  const r = spawnSync(BIN, [name], { encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
  if (r.error) return { ok: false, error: `run failed: ${r.error.message}` };
  if (r.status !== 0) return { ok: false, error: `exit ${r.status}: ${(r.stderr ?? '').trim().split('\n')[0]}` };
  try {
    return { ok: true, doc: JSON.parse(r.stdout) };
  } catch {
    return { ok: false, error: 'output is not one JSON document' };
  }
}

// The Node oracle: the project's entry run as ESM in a child process, natives from native.json.
function runNode(dir, natives) {
  const entry = path.join(dir, 'scenario.js');
  const env = { ...process.env, VN_NATIVES: JSON.stringify(natives) };
  delete env.NODE_TEST_CONTEXT;
  const r = spawnSync(process.execPath, ['--import', path.join(here, 'natives-register.mjs'), path.join(ROOT, 'tooling/oracle/run.mjs'), entry],
    { env, encoding: 'utf8', timeout: 120000, maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) return { ok: false, error: `oracle exit ${r.status}: ${(r.stderr ?? '').trim().split('\n').slice(0, 2).join(' | ')}` };
  return { ok: true, doc: JSON.parse(r.stdout) };
}

function withoutName(doc) {
  const { scenario, ...rest } = doc;
  return rest;
}

function main() {
  const names = listProjects(dirArg);
  const projects = [];
  const outcomes = [];
  for (const name of names) {
    const dir = path.join(dirArg, name);
    const natives = nativesOf(dir);
    const files = readProject(dir);
    const hasVue = Object.keys(files).some((f) => f.endsWith('.vue'));
    // target 'test': the scenarios use the test-only globals (trace, testHost), which the native profile rejects (VN4016).
    const c = compileProject({ entry: 'scenario.js', files, target: 'test' });
    if (!c.ok) {
      const d = c.diagnostics.find((x) => x.severity === 'error');
      outcomes.push({ name, outcome: 'compile-error', reason: d ? `${d.code} ${d.message} (${d.file})` : 'not compiled' });
      continue;
    }
    const compiled = c.modules.filter((m) => m.rust !== null);
    projects.push({ name, dir, hasVue, natives: nativeEntries(natives), nativeJson: natives, compiled, entryId: c.entryId });
    outcomes.push({ name, outcome: null });
  }

  if (projects.length > 0) {
    writeCrate(projects);
    const b = build();
    if (!b.ok) {
      console.log(`BUILD FAILED: ${b.output.split('\n').filter((l) => /^error/.test(l)).slice(0, 3).join(' | ') || b.output.slice(0, 400)}`);
      process.exitCode = 1;
      return;
    }
  }

  let failures = 0;
  projects.forEach((p) => {
    const o = outcomes.find((x) => x.name === p.name);
    const run = runRust(p.name);
    if (!run.ok) return Object.assign(o, { outcome: 'FAIL', reason: run.error });
    if (run.doc.result === 'panic') return Object.assign(o, { outcome: 'FAIL', reason: `panic: ${String(run.doc.error).slice(0, 200)}` });
    const expFile = path.join(p.dir, 'expected.json');
    // --write-expected regenerates the Node oracle's document; a project with a .vue file keeps its hand-written one.
    if (flag('--write-expected') && !p.hasVue) {
      const node = runNode(p.dir, p.nativeJson);
      if (!node.ok) return Object.assign(o, { outcome: 'FAIL', reason: node.error });
      writeFileSync(expFile, `${JSON.stringify(withoutName(node.doc))}\n`);
    }
    if (!existsSync(expFile)) return Object.assign(o, { outcome: 'FAIL', reason: 'missing expected.json' });
    const expected = JSON.parse(readFileSync(expFile, 'utf8'));
    const diff = compareDocs(withoutName(run.doc), expected);
    Object.assign(o, diff === null ? { outcome: 'pass' } : { outcome: 'FAIL', reason: describeDiff(diff) });
  });

  const counts = {};
  for (const o of outcomes) {
    counts[o.outcome ?? 'pass'] = (counts[o.outcome ?? 'pass'] ?? 0) + 1;
    if (o.outcome !== 'pass') {
      failures += 1;
      console.log(`${o.outcome.padEnd(13)} ${o.name}${o.reason ? `  -- ${String(o.reason).slice(0, 240)}` : ''}`);
    }
  }
  console.log(`projects ${outcomes.length}: pass ${counts.pass ?? 0}, FAIL ${counts.FAIL ?? 0}, compile-error ${counts['compile-error'] ?? 0}`);
  process.exitCode = failures === 0 ? 0 : 1;
}

main();
