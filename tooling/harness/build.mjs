// Harness library (WP-C1b): compiles scenario modules, writes one throw-away cargo crate under target/scenarios/language
// (path dependencies on crates/value and crates/testkit; main.rs holds the scenario table and calls vn_testkit::scenario_main)
// and builds it in the private target dir target/c1b. Files are rewritten only when their content changes, so cargo
// rebuilds only what changed.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(here, '../..');
// The cargo target dir: CARGO_TARGET_DIR when the caller sets it (each WP has a private one), else target/c1b.
export const TARGET_DIR = process.env.CARGO_TARGET_DIR || path.join(ROOT, 'target', 'c1b');
export const CRATE_DIR = path.join(ROOT, 'target', 'scenarios', 'language');
export const BINARY = path.join(TARGET_DIR, 'debug', 'vn-scenarios');
// The Vue scenario crate (WP-C1c follow-up, `run-language.mjs --with-vue`): same modules, realm setup registers vn-runtime's
// "vue" native module. It shares TARGET_DIR with the language crate, so the dependencies compile once.
export const VUE_CRATE_DIR = path.join(ROOT, 'target', 'scenarios', 'vue');
export const VUE_BINARY = path.join(TARGET_DIR, 'debug', 'vn-vue-scenarios');

export function cargoEnv() {
  return {
    ...process.env,
    PATH: `${path.join(ROOT, 'toolchain', 'cargo', 'bin')}:${process.env.PATH}`,
    RUSTUP_HOME: path.join(ROOT, 'toolchain', 'rustup'),
    CARGO_HOME: path.join(ROOT, 'toolchain', 'cargo'),
    CARGO_INCREMENTAL: '0',
    CARGO_TARGET_DIR: TARGET_DIR,
  };
}

function writeIfChanged(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  writeFileSync(file, text);
}

// The async runtime that async modules import as crate::vn_async (WP-C1c). WP-B5 (promises) has not landed while this
// text is a stand-in: frames are rooted JavaScript arrays, await of a value is ready at once, and an async call runs its
// body to completion, returning the body's value (a throw is lost, and no promise exists). Once WP-B5 defines
// `pub fn async_start` in crates/value, the file re-exports it instead (see asyncRuntimeRs).
const ASYNC_STANDIN_RS = `// Stand-in for the async runtime (WP-C1c): WP-B5 has not landed. Generated by tooling/harness/build.mjs. Do not edit.
use std::future::Future;
use std::pin::Pin;
use std::task::{Context, Poll, Waker};
use vn_value::*;

pub fn new_frame(rt: &Rt, slots: usize) -> ObjRef {
    let f = rt.new_array(vec![Value::Undefined; slots]);
    let _ = rt.root(&Value::Object(f));
    f
}

pub fn frame_get(rt: &Rt, f: ObjRef, i: usize) -> Value {
    match rt.get_own_property(f, &PropKey::Index(i as u32)) {
        Ok(Some(Prop::Data { value, .. })) => value,
        _ => Value::Undefined,
    }
}

pub fn frame_set(rt: &Rt, f: ObjRef, i: usize, v: Value) {
    if rt.set_v_strict(&Value::Object(f), &PropKey::Index(i as u32), v).is_err() {
        panic!("stand-in async runtime: frame slot write failed");
    }
}

pub fn async_start(rt: &Rt, frame: ObjRef, body: Pin<Box<dyn Future<Output = Res<Value>>>>) -> Value {
    let _ = (rt, frame);
    let mut body = body;
    let mut cx = Context::from_waker(Waker::noop());
    match body.as_mut().poll(&mut cx) {
        Poll::Ready(Ok(v)) => v,
        Poll::Ready(Err(_)) => Value::Undefined,
        Poll::Pending => panic!("stand-in async runtime: a body suspended without a promise"),
    }
}

pub fn await_value(rt: &Rt, v: Value) -> impl Future<Output = Res<Value>> {
    let _ = rt;
    std::future::ready(Ok(v))
}
`;

// The text of src/vn_async.rs for a scenario crate: the WP-B5 re-export when crates/value defines async_start, else the
// stand-in above.
export function asyncRuntimeRs() {
  const landed = spawnSync('grep', ['-rl', 'pub fn async_start', path.join(ROOT, 'crates', 'value', 'src')], { encoding: 'utf8' });
  if (landed.status === 0 && landed.stdout.trim() !== '') {
    return [
      '// Re-export of the WP-B5 async runtime (WP-C1c). Generated by tooling/harness/build.mjs. Do not edit.',
      'pub use vn_value::builtins::promise::{async_start, await_value, frame_get, frame_set, new_frame};',
      '',
    ].join('\n');
  }
  return ASYNC_STANDIN_RS;
}

// Writes src/vn_async.rs into a crate source directory.
export function writeAsyncRuntime(srcDir) {
  writeIfChanged(path.join(srcDir, 'vn_async.rs'), asyncRuntimeRs());
}

// modules: [{ name, rust }]. Module i is src/s<i>.rs; the table maps each scenario name to its entry.
// opts: { dir, pkg, vue }. vue: the crate depends on vn-runtime and its realm setup registers the "vue" native module.
export function writeCrate(modules, { dir = CRATE_DIR, pkg = 'vn-scenarios', vue = false } = {}) {
  const deps = {
    value: path.join(ROOT, 'crates', 'value'),
    testkit: path.join(ROOT, 'crates', 'testkit'),
    runtime: path.join(ROOT, 'crates', 'runtime'),
  };
  writeIfChanged(path.join(dir, 'Cargo.toml'), [
    '# Generated by tooling/harness (WP-C1b/C1c). Do not edit.',
    '[package]', `name = "${pkg}"`, 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[dependencies]',
    `vn-value = { path = ${JSON.stringify(deps.value)} }`,
    `vn-testkit = { path = ${JSON.stringify(deps.testkit)} }`,
    ...(vue ? [`vn-runtime = { path = ${JSON.stringify(deps.runtime)} }`] : []), '',
    '[workspace]', '',
  ].join('\n'));
  modules.forEach((m, i) => writeIfChanged(path.join(dir, 'src', `s${i}.rs`), m.rust));
  writeAsyncRuntime(path.join(dir, 'src'));
  const names = modules.map((m, i) => `    (${JSON.stringify(m.name)}, entry${i} as ScenarioFn),`);
  const entries = modules.map((m, i) => `fn entry${i}(rt: &Rt) -> Res<ScenarioEntry> {\n    entry(rt, s${i}::MODULE.specifier)\n}`);
  const regs = modules.map((_, i) => `    rt.register_module_def(s${i}::def());`);
  const mods = [...modules.map((_, i) => `mod s${i};`), 'mod vn_async;'];
  const main = [
    '// Generated by tooling/harness (WP-C1b/C1c). Do not edit.',
    vue ? 'use vn_testkit::{scenario_main_with_setup, ScenarioEntry, ScenarioFn};' : 'use vn_testkit::{scenario_main, ScenarioEntry, ScenarioFn};',
    'use vn_value::{Res, Rt, Value};',
    ...mods,
    '',
    'fn register(rt: &Rt) {',
    ...regs,
    '}',
    '',
    'fn entry(rt: &Rt, spec: &str) -> Res<ScenarioEntry> {',
    '    register(rt);',
    '    let m = rt.load_module(spec)?;',
    '    let run = match rt.module_export_cell(m, "run")? {',
    '        Some(c) => rt.cell_get(c),',
    '        None => Value::Undefined,',
    '    };',
    '    Ok(ScenarioEntry { run })',
    '}',
    '',
    ...entries,
    '',
    ...(vue ? [
      '// Realm setup: the native module "vue" of the runtime (exports of vn-runtime::exports::all).',
      'fn setup(rt: &Rt) {',
      '    let _ = vn_runtime::exports::register_vue_module(rt);',
      '}',
      '',
    ] : []),
    'fn main() {',
    vue ? '    scenario_main_with_setup(&[' : '    scenario_main(&[',
    ...names,
    vue ? '    ], setup);' : '    ]);',
    '}',
    '',
  ].join('\n');
  writeIfChanged(path.join(dir, 'src', 'main.rs'), main);
}

// Builds the crate; returns { ok, output }. Output is the cargo stderr (empty on success).
export function buildCrate(dir = CRATE_DIR) {
  const r = spawnSync('cargo', ['build', '--quiet', '--manifest-path', path.join(dir, 'Cargo.toml')], {
    env: cargoEnv(),
    encoding: 'utf8',
    timeout: 580000,
  });
  return { ok: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim() };
}

// Runs one scenario in its own process (30 s limit). Returns { ok, doc, error }.
export function runOne(name, binary = BINARY) {
  const r = spawnSync(binary, [name], { encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
  if (r.error) return { ok: false, error: `run failed: ${r.error.message}` };
  if (r.status !== 0) return { ok: false, error: `exit ${r.status}: ${(r.stderr ?? '').trim().split('\n')[0]}` };
  try {
    return { ok: true, doc: JSON.parse(r.stdout) };
  } catch {
    return { ok: false, error: 'output is not one JSON document' };
  }
}
