// Harness library (WP-C1b): compiles scenario modules, writes one throw-away cargo crate under target/scenarios/language
// (path dependencies on crates/value and crates/testkit; main.rs holds the scenario table and calls vn_testkit::scenario_main)
// and builds it in the private target dir target/c1b. Files are rewritten only when their content changes, so cargo
// rebuilds only what changed.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(here, '../..');
// The cargo target dir: CARGO_TARGET_DIR when the caller sets it (each WP has a private one), else target/c1b.
export const TARGET_DIR = process.env.CARGO_TARGET_DIR || path.join(ROOT, 'target', 'c1b');
export const CRATE_DIR = path.join(ROOT, 'target', 'scenarios', 'language');
export const BINARY = path.join(TARGET_DIR, 'debug', 'vn-scenarios');

export function cargoEnv() {
  return {
    ...process.env,
    PATH: `${path.join(ROOT, 'toolchain', 'cargo', 'bin')}:${process.env.PATH}`,
    RUSTUP_HOME: path.join(ROOT, 'toolchain', 'rustup'),
    CARGO_HOME: path.join(ROOT, 'toolchain', 'cargo'),
    CARGO_INCREMENTAL: '0',
    CARGO_TARGET_DIR: TARGET_DIR,
  };
}

function writeIfChanged(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  writeFileSync(file, text);
}

// modules: [{ name, rust }]. Module i is src/s<i>.rs; the table maps each scenario name to its entry.
export function writeCrate(modules) {
  const deps = {
    value: path.join(ROOT, 'crates', 'value'),
    testkit: path.join(ROOT, 'crates', 'testkit'),
  };
  writeIfChanged(path.join(CRATE_DIR, 'Cargo.toml'), [
    '# Generated by tooling/harness (WP-C1b). Do not edit.',
    '[package]', 'name = "vn-scenarios"', 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[dependencies]',
    `vn-value = { path = ${JSON.stringify(deps.value)} }`,
    `vn-testkit = { path = ${JSON.stringify(deps.testkit)} }`, '',
    '[workspace]', '',
  ].join('\n'));
  modules.forEach((m, i) => writeIfChanged(path.join(CRATE_DIR, 'src', `s${i}.rs`), m.rust));
  const names = modules.map((m, i) => `    (${JSON.stringify(m.name)}, entry${i} as ScenarioFn),`);
  const entries = modules.map((m, i) => `fn entry${i}(rt: &Rt) -> Res<ScenarioEntry> {\n    entry(rt, s${i}::MODULE.specifier)\n}`);
  const regs = modules.map((_, i) => `    rt.register_module_def(s${i}::def());`);
  const mods = modules.map((_, i) => `mod s${i};`);
  const main = [
    '// Generated by tooling/harness (WP-C1b). Do not edit.',
    'use vn_testkit::{scenario_main, ScenarioEntry, ScenarioFn};',
    'use vn_value::{Res, Rt, Value};',
    ...mods,
    '',
    'fn register(rt: &Rt) {',
    ...regs,
    '}',
    '',
    'fn entry(rt: &Rt, spec: &str) -> Res<ScenarioEntry> {',
    '    register(rt);',
    '    let m = rt.load_module(spec)?;',
    '    let run = match rt.module_export_cell(m, "run")? {',
    '        Some(c) => rt.cell_get(c),',
    '        None => Value::Undefined,',
    '    };',
    '    Ok(ScenarioEntry { run })',
    '}',
    '',
    ...entries,
    '',
    'fn main() {',
    '    scenario_main(&[',
    ...names,
    '    ]);',
    '}',
    '',
  ].join('\n');
  writeIfChanged(path.join(CRATE_DIR, 'src', 'main.rs'), main);
}

// Builds the crate; returns { ok, output }. Output is the cargo stderr (empty on success).
export function buildCrate() {
  const r = spawnSync('cargo', ['build', '--quiet', '--manifest-path', path.join(CRATE_DIR, 'Cargo.toml')], {
    env: cargoEnv(),
    encoding: 'utf8',
    timeout: 580000,
  });
  return { ok: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim() };
}

// Runs one scenario in its own process (30 s limit). Returns { ok, doc, error }.
export function runOne(name) {
  const r = spawnSync(BINARY, [name], { encoding: 'utf8', timeout: 30000, maxBuffer: 64 * 1024 * 1024 });
  if (r.error) return { ok: false, error: `run failed: ${r.error.message}` };
  if (r.status !== 0) return { ok: false, error: `exit ${r.status}: ${(r.stderr ?? '').trim().split('\n')[0]}` };
  try {
    return { ok: true, doc: JSON.parse(r.stdout) };
  } catch {
    return { ok: false, error: 'output is not one JSON document' };
  }
}
