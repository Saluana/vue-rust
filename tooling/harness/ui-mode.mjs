// UI scenario mode (WP-T2): `run-language.mjs --with-vue --ui` runs every tests/ui/cases/<group>/<name>/scenario.js as a
// project (its .vue files compiled with it, compileProject), in one generated crate target/scenarios/ui. The crate links
// vn-uikit, whose realm setup (vn_uikit::ui_setup) registers the "vue" native module and installs the UI testHost. Each
// document is compared with the golden tests/ui/golden/<group>/<name>.json (structural compare, tooling/oracle/compare.mjs).
// The ledger tests/ui/status.json holds "pass" or {"blocked": reason} per scenario: a blocked scenario that passes must be
// flipped to "pass" (ratchet); a scenario without an entry must pass.
//   node tooling/harness/run-language.mjs --with-vue --ui [--filter text] [--write-status] [--verbose]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { compileProject } from '../../compiler/project/index.mjs';
import { modulesTableRs, moduleFileName } from '../../compiler/project/table.mjs';
import { compareDocs, describeDiff } from '../oracle/compare.mjs';
import { nativeEntries, nativeRustRs } from './natives.mjs';
import { ROOT, TARGET_DIR, cargoEnv, runOne, writeAsyncRuntime } from './build.mjs';

const CASES = path.join(ROOT, 'tests/ui/cases');
const GOLDEN = path.join(ROOT, 'tests/ui/golden');
const LEDGER = path.join(ROOT, 'tests/ui/status.json');
const CRATE = path.join(ROOT, 'target', 'scenarios', 'ui');
const BIN = path.join(TARGET_DIR, 'debug', 'vn-ui-scenarios');

function writeIfChanged(file, text) {
  mkdirSync(path.dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  writeFileSync(file, text);
}

// Every scenario directory (one that holds scenario.js) below root, in name order.
function listCases(root) {
  const out = [];
  const walk = (d) => {
    const entries = readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1));
    if (entries.some((e) => e.isFile() && e.name === 'scenario.js')) {
      out.push(d);
      return;
    }
    for (const e of entries) if (e.isDirectory()) walk(path.join(d, e.name));
  };
  walk(root);
  return out;
}

// Every source file of a case (scenario.js, its .vue components, and any module), keyed by its path under the case.
function readCase(dir) {
  const files = {};
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(js|mjs|ts|vue)$/.test(e.name)) files[path.relative(dir, p).split(path.sep).join('/')] = readFileSync(p, 'utf8');
    }
  };
  walk(dir);
  return files;
}

// One directory per project (mod.rs, natives.rs, modules.rs, m<k>.rs), main.rs with the table and the UI realm setup.
function writeCrate(projects) {
  writeIfChanged(path.join(CRATE, 'Cargo.toml'), [
    '# Generated by tooling/harness/ui-mode.mjs (WP-T2). Do not edit.',
    '[package]', 'name = "vn-ui-scenarios"', 'version = "0.0.1"', 'edition = "2024"', 'publish = false', '',
    '[dependencies]',
    `vn-value = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'value'))} }`,
    `vn-testkit = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'testkit'))} }`,
    `vn-runtime = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'runtime'))} }`,
    `vn-uikit = { path = ${JSON.stringify(path.join(ROOT, 'crates', 'uikit'))} }`, '',
    '[workspace]', '',
  ].join('\n'));
  writeAsyncRuntime(path.join(CRATE, 'src'));
  const mains = ['mod vn_async;'];
  const entries = [];
  projects.forEach((p, j) => {
    const dir = path.join(CRATE, 'src', `p${j}`);
    const mods = p.compiled.map((_, k) => `pub mod ${moduleFileName(k)};`);
    writeIfChanged(path.join(dir, 'mod.rs'), [
      '// Generated by tooling/harness/ui-mode.mjs (WP-T2). Do not edit.',
      'pub mod natives;', 'pub mod modules;', ...mods, '',
    ].join('\n'));
    writeIfChanged(path.join(dir, 'natives.rs'), nativeRustRs(p.natives));
    writeIfChanged(path.join(dir, 'modules.rs'), modulesTableRs(p.compiled, p.entryId));
    p.compiled.forEach((m, k) => writeIfChanged(path.join(dir, `${moduleFileName(k)}.rs`), m.rust));
    mains.push(`mod p${j};`);
    entries.push([
      `fn entry${j}(rt: &Rt) -> Res<ScenarioEntry> {`,
      `    p${j}::natives::register(rt);`,
      `    for d in p${j}::modules::defs() {`,
      '        rt.register_module_def(d);',
      '    }',
      `    let m = rt.load_module(p${j}::modules::entry())?;`,
      '    let run = match rt.module_export_cell(m, "run")? {',
      '        Some(c) => rt.cell_get(c),',
      '        None => Value::Undefined,',
      '    };',
      '    Ok(ScenarioEntry { run })',
      '}',
    ].join('\n'));
  });
  const table = projects.map((p, j) => `    (${JSON.stringify(p.name)}, entry${j} as ScenarioFn),`);
  writeIfChanged(path.join(CRATE, 'src', 'main.rs'), [
    '// Generated by tooling/harness/ui-mode.mjs (WP-T2). Do not edit.',
    'use vn_testkit::{scenario_main_with_setup, ScenarioEntry, ScenarioFn};',
    'use vn_value::{Res, Rt, Value};',
    ...mains, '', ...entries, '',
    '// Realm setup: the "vue" module, the document and the UI testHost (vn_uikit::ui_setup).',
    'fn setup(rt: &Rt) {', '    vn_uikit::ui_setup(rt);', '}', '',
    'fn main() {', '    scenario_main_with_setup(&[', ...table, '    ], setup);', '}', '',
  ].join('\n'));
}

function build() {
  const r = spawnSync('cargo', ['build', '--quiet', '--manifest-path', path.join(CRATE, 'Cargo.toml')], {
    env: cargoEnv(), encoding: 'utf8', timeout: 580000,
  });
  return { ok: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim() };
}

// The reason of a failing scenario: a panic, a thrown error where the golden expects a result, or the first difference.
function reasonOf(doc, golden, diff) {
  if (doc.result === 'panic') return `panic: ${String(doc.error).slice(0, 200)}`;
  if (doc.result === 'throw' && golden.result !== 'throw') {
    const err = doc.error && typeof doc.error === 'object' ? doc.error : { message: String(doc.error) };
    return `threw ${err.name ?? err.cls ?? 'error'}: ${String(err.message ?? '')}`;
  }
  return describeDiff(diff);
}

// The cause class of a failing scenario, from its exact reason. The ledger records "<class>: <reason>".
export function causeOf(outcome, reason) {
  if (outcome === 'compile-error') return 'compile error';
  if (/does not provide an export named '([^']+)'/.test(reason)) {
    return `missing feature: vue export '${/export named '([^']+)'/.exec(reason)[1]}' is not provided by vn-runtime`;
  }
  if (/extension slot is owned by another subsystem/.test(reason)) {
    return 'runtime defect: reactive() wraps a DOM element handle, whose extension slot is taken';
  }
  if (/UnsupportedStyleProperty/.test(reason)) return 'missing feature: vn-dom rejects a style property';
  if (/^panic/.test(reason)) return 'panic';
  if (/^first difference at/.test(reason)) return 'wrong output: the trace differs from the golden';
  return 'unclassified';
}

function printGroups(rows) {
  const groups = new Map();
  for (const r of rows) {
    const g = r.name.split('/')[0];
    if (!groups.has(g)) groups.set(g, { total: 0, pass: 0, blocked: 0, FAIL: 0, 'compile-error': 0 });
    const c = groups.get(g);
    c.total += 1;
    if (r.outcome === 'pass') c.pass += 1;
    else if (r.outcome === 'compile-error') c['compile-error'] += 1;
    else c.FAIL += 1;
  }
  console.log('group            total  pass  FAIL  compile-error');
  for (const [g, c] of [...groups.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    console.log(`${g.padEnd(16)} ${String(c.total).padStart(5)} ${String(c.pass).padStart(5)} ${String(c.FAIL).padStart(5)} ${String(c['compile-error']).padStart(14)}`);
  }
}

function sortKeys(o) {
  return Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
}

// Runs the UI scenarios. opts: { filter, writeStatus, verbose }. Exit status 1 on any unexpected outcome.
export function runUiScenarios({ filter = '', writeStatus = false, verbose = false } = {}) {
  const dirs = listCases(CASES).filter((d) => path.relative(CASES, d).split(path.sep).join('/').includes(filter));
  const rows = [];
  const projects = [];
  for (const dir of dirs) {
    const name = path.relative(CASES, dir).split(path.sep).join('/');
    const c = compileProject({ entry: 'scenario.js', files: readCase(dir), target: 'test' });
    if (!c.ok) {
      const d = c.diagnostics.find((x) => x.severity === 'error');
      rows.push({ name, outcome: 'compile-error', reason: d ? `${d.code} ${d.message} (${d.file})` : 'not compiled' });
      continue;
    }
    const compiled = c.modules.filter((m) => m.rust !== null);
    projects.push({ name, compiled, entryId: c.entryId, natives: nativeEntries({}) });
    rows.push({ name, outcome: null });
  }
  if (projects.length > 0) {
    writeCrate(projects);
    const b = build();
    if (!b.ok) {
      console.log(`BUILD FAILED: ${b.output.split('\n').filter((l) => /^error/.test(l)).slice(0, 6).join(' | ') || b.output.slice(0, 600)}`);
      process.exitCode = 1;
      return;
    }
  }
  for (const r of rows) {
    if (r.outcome !== null) continue;
    const run = runOne(r.name, BIN);
    if (!run.ok) {
      r.outcome = 'FAIL';
      r.reason = run.error;
      continue;
    }
    const goldenFile = path.join(GOLDEN, `${r.name}.json`);
    if (!existsSync(goldenFile)) {
      r.outcome = 'FAIL';
      r.reason = 'missing golden';
      continue;
    }
    const golden = JSON.parse(readFileSync(goldenFile, 'utf8'));
    const diff = compareDocs(run.doc, golden);
    if (diff === null) r.outcome = 'pass';
    else {
      r.outcome = 'FAIL';
      r.reason = reasonOf(run.doc, golden, diff);
    }
  }
  const ledger = existsSync(LEDGER) ? JSON.parse(readFileSync(LEDGER, 'utf8')) : {};
  const next = {};
  let unexpected = 0;
  const counts = { pass: 0, FAIL: 0, blocked: 0, 'compile-error': 0 };
  for (const r of rows) {
    const entry = ledger[r.name];
    const isBlocked = entry !== undefined && entry !== 'pass';
    let status;
    if (r.outcome === 'pass') {
      status = 'pass';
      next[r.name] = 'pass';
      if (isBlocked) {
        unexpected += 1;
        console.log(`ratchet   ${r.name}  -- blocked in the ledger but passes: flip it to "pass"`);
      }
    } else {
      status = isBlocked ? 'blocked' : r.outcome === 'compile-error' ? 'compile-error' : 'FAIL';
      next[r.name] = { blocked: `${causeOf(r.outcome, r.reason ?? '')}: ${r.reason ?? r.outcome}` };
      if (!isBlocked) unexpected += 1;
    }
    counts[status] += 1;
    if (verbose || (status !== 'pass' && !isBlocked)) {
      console.log(`${status.padEnd(13)} ${r.name}${r.reason ? `  -- ${String(r.reason).slice(0, 240)}` : ''}`);
    }
  }
  if (writeStatus) writeFileSync(LEDGER, `${JSON.stringify(sortKeys(next), null, 1)}\n`);
  printGroups(rows);
  console.log(`scenarios ${rows.length}: pass ${counts.pass}, FAIL ${counts.FAIL}, blocked ${counts.blocked}, compile-error ${counts['compile-error']}; ${unexpected} unexpected`);
  process.exitCode = unexpected === 0 ? 0 : 1;
}
