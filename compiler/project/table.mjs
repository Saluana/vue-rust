// The Rust module table of a compiled project (WP-C1c). Each compiled module is one file `m<k>.rs` (k = index in the
// sorted module list); `modules.rs` lists their ModuleDef statics. The harness puts the files in one directory with a
// `mod.rs` that declares them (`pub mod m0; ... pub mod modules;`).
import { rstr } from '../emit/names.mjs';

export function moduleFileName(k) {
  return `m${k}`;
}

// modules: the compiled modules of a project in order (only those with rust !== null), entryId: the entry specifier.
export function modulesTableRs(modules, entryId) {
  const names = modules.map((_, k) => moduleFileName(k));
  const lines = [
    '// Generated by the vue-native compiler (WP-C1c) from a project graph. Do not edit.',
    '#![allow(dead_code)]',
    'use vn_value::ModuleDef;',
  ];
  if (names.length > 0) lines.push(`use super::{${names.join(', ')}};`);
  lines.push('', `pub fn entry() -> &'static str {\n    ${rstr(entryId)}\n}`, '');
  const defs = names.map((n) => `&${n}::MODULE`).join(', ');
  lines.push(`static DEFS: &[&ModuleDef] = &[${defs}];`, '');
  lines.push(`pub fn defs() -> &'static [&'static ModuleDef] {\n    DEFS\n}`, '');
  return lines.join('\n');
}
