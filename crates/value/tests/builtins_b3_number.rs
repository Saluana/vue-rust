#[test]
fn lengths_names_constants_and_attributes() {
    let rt = Rt::new();
    let number = global(&rt, "Number");
    let proto = rt.get_str(&number, "prototype").expect("prototype");
    let mut fails = Vec::new();
    for (name, len) in PROTO_LENGTHS {
        let f = rt.get_str(&proto, name).expect("method");
        if rt.get_str(&f, "length").expect("length") != Value::Number(f64::from(*len)) {
            fails.push(format!("Number.prototype.{name}: length"));
        }
        if proto_flags(&rt, &proto, name) != Some(Flags::HIDDEN) {
            fails.push(format!("Number.prototype.{name}: flags"));
        }
    }
    for (name, len) in STATIC_LENGTHS {
        let f = rt.get_str(&number, name).expect("static");
        if rt.get_str(&f, "length").expect("length") != Value::Number(f64::from(*len)) {
            fails.push(format!("Number.{name}: length"));
        }
    }
    for (name, v) in CONSTANTS {
        let got = rt.get_str(&number, name).expect("constant");
        match got {
            Value::Number(n) if n.to_bits() == v.to_bits() => {}
            other => fails.push(format!("Number.{name} = {other:?}, V8 {v}")),
        }
        if proto_flags(&rt, &number, name) != Some(Flags::NONE) {
            fails.push(format!("Number.{name}: constants must be non-writable, non-enumerable, non-configurable"));
        }
    }
    // Inherited toLocaleString (Object.prototype) is fine; Number.prototype itself must not define one.
    if proto_flags(&rt, &proto, "toLocaleString").is_some() {
        fails.push("Number.prototype must have no own toLocaleString".to_string());
    }
    let global_obj = rt.intrinsic(Intrinsic::Global);
    let flags = rt.get_own_property(global_obj, &PropKey::from_str("Number")).expect("own").map(|p| p.flags());
    if flags != Some(Flags::HIDDEN) {
        fails.push(format!("global Number flags {flags:?}"));
    }
    assert!(fails.is_empty(), "Number shape differs:\n{}", fails.join("\n"));
}

#[test]
fn wrappers_symbols_and_argument_order() {
    let rt = Rt::new();
    let number = global(&rt, "Number");
    let s = Value::str;
    let mut fails = Vec::new();
    let mut check = |label: &str, got: String, want: &str| {
        if got != want {
            fails.push(format!("{label}: got {got}, V8 {want}"));
        }
    };
    let w = rt.construct(&number, &[Value::Number(255.0)], &number).expect("new Number");
    check("wrapper valueOf", show(&rt, &call_method(&rt, "valueOf", &w, &[])), "255");
    check("wrapper toString(16)", show(&rt, &call_method(&rt, "toString", &w, &[Value::Number(16.0)])), r#""ff""#);
    check("Number(wrapper)", show(&rt, &rt.call(&number, &Value::Undefined, &[w.clone()])), "255");
    let empty = rt.construct(&number, &[], &number).expect("new Number()");
    check("new Number() valueOf", show(&rt, &call_method(&rt, "valueOf", &empty, &[])), "0");
    let proto = Value::Object(rt.intrinsic(Intrinsic::NumberPrototype));
    check("Number.prototype.valueOf()", show(&rt, &call_method(&rt, "valueOf", &proto, &[])), "0");
    check("Number.prototype.toString(2)", show(&rt, &call_method(&rt, "toString", &proto, &[Value::Number(2.0)])), r#""0""#);
    let object_tostring = rt.get_str(&Value::Object(rt.intrinsic(Intrinsic::ObjectPrototype)), "toString").expect("toString");
    check("Object.prototype.toString of a wrapper", show(&rt, &rt.call(&object_tostring, &w, &[])), r#""[object Number]""#);
    check("Object.prototype.toString of Number.prototype", show(&rt, &rt.call(&object_tostring, &proto, &[])), r#""[object Number]""#);
    let sym = Value::Symbol(rt.new_symbol(None));
    check("Number(symbol)", show(&rt, &rt.call(&number, &Value::Undefined, &[sym.clone()])), "throw:TypeError");
    check("new Number(symbol)", show(&rt, &rt.construct(&number, &[sym.clone()], &number)), "throw:TypeError");
    check("toString with a symbol this", show(&rt, &call_method(&rt, "toString", &sym, &[])), "throw:TypeError");
    check("toString of a plain object this", show(&rt, &call_method(&rt, "toString", &Value::Object(rt.new_object()), &[])), "throw:TypeError");
    // this is checked before the radix is converted (no log), and the radix is converted once (a log)
    let r = call_method(&rt, "toString", &s("x"), &[tagged(&rt, "r", Value::Number(2.0))]);
    check("this checked before the radix", show(&rt, &r), "throw:TypeError");
    check("this check logs nothing", take_log(), "");
    let r = call_method(&rt, "toString", &Value::Number(255.0), &[tagged(&rt, "r", Value::Number(16.0))]);
    check("radix conversion", show(&rt, &r), r#""ff""#);
    check("radix converted once", take_log(), "r.valueOf");
    let r = call_method(&rt, "toFixed", &Value::Number(1.5), &[tagged(&rt, "d", Value::Number(2.0))]);
    check("toFixed digits", show(&rt, &r), r#""1.50""#);
    check("toFixed logs digits", take_log(), "d.valueOf");
    assert!(fails.is_empty(), "wrapper and order behaviour differs from V8:\n{}", fails.join("\n"));
}

#[test]
fn parse_functions_are_installed() {
    let rt = Rt::new();
    let number = global(&rt, "Number");
    let parse_float = rt.get_str(&number, "parseFloat").expect("parseFloat");
    let parse_int = rt.get_str(&number, "parseInt").expect("parseInt");
    assert!(rt.is_callable(&parse_float) && rt.is_callable(&parse_int));
    assert_eq!(show(&rt, &rt.call(&parse_int, &Value::Undefined, &[Value::str("0x1F")])), "31");
    assert_eq!(show(&rt, &rt.call(&parse_float, &Value::Undefined, &[Value::str(" 3.5e2xyz")])), "350");
    // Number.parseFloat and Number.parseInt are the global function objects installed by global::install.
    let global_obj = rt.intrinsic(Intrinsic::Global);
    for name in ["parseFloat", "parseInt"] {
        let global_fn = match rt.get_own_property(global_obj, &PropKey::from_str(name)).expect("own property") {
            Some(Prop::Data { value, .. }) => value,
            other => panic!("the global {name} must be a data property, found {other:?}"),
        };
        assert_eq!(rt.get_str(&number, name).expect("Number static"), global_fn, "Number.{name} must be the global {name}");
    }
}
