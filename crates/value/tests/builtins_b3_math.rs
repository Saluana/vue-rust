thread_local! {
    static LOG: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
}

fn log(entry: String) {
    LOG.with(|l| l.borrow_mut().push(entry));
}

fn take_log() -> String {
    LOG.with(|l| l.borrow_mut().drain(..).collect::<Vec<_>>().join(","))
}

fn tagged(rt: &Rt, tag: &str, value: f64) -> Value {
    let o = rt.new_object();
    let data = vec![Value::str(tag), Value::Number(value)];
    let vo = rt.new_native_function(tagged_value_of, "valueOf", 0, data);
    rt.define_data(o, PropKey::from_str("valueOf"), Value::Object(vo), Flags::HIDDEN).expect("define");
    Value::Object(o)
}

fn tagged_value_of(rt: &Rt, c: &Call<'_>) -> Res<Value> {
    let data = rt.fn_data(c.callee);
    let tag = rt.to_string(&data[0])?.to_rust_string_lossy();
    log(format!("{tag}.valueOf"));
    Ok(data[1].clone())
}

fn check(label: &str, got: &str, want: &str, log: &str, want_log: &str, fails: &mut Vec<String>) {
    if got != want || log != want_log {
        fails.push(format!("{label}: result {got} (V8 {want}); log [{log}] (V8 [{want_log}])"));
    }
}

#[test]
fn table_matches_v8_with_the_approx_rule() {
    let rt = Rt::new();
    let mut bad = Vec::new();
    let mut inexact: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    for (name, args, want, approx) in MATH_CASES {
        let got = math_call(&rt, name, args);
        let exact = same_bits(got, *want);
        let entry = inexact.entry(name).or_insert((0, 0));
        entry.1 += 1;
        if !exact {
            entry.0 += 1;
        }
        let ok = if *approx {
            exact || (got.is_finite() && want.is_finite() && ulp_distance(got, *want) <= 1)
        } else {
            exact
        };
        if !ok {
            bad.push(format!("Math.{name}({args:?}): V8 {} ({:#x}), got {} ({:#x})", want, want.to_bits(), got, got.to_bits()));
        }
    }
    let summary: Vec<String> = inexact.iter().map(|(n, (x, t))| format!("{n} {x}/{t}")).collect();
    eprintln!("WP-B3 Math: results not bit-identical to V8 (count/total per function): {}", summary.join(", "));
    assert!(bad.is_empty(), "{} Math cases differ from V8:\n{}", bad.len(), bad.join("\n"));
}

#[test]
fn lengths_constants_and_absent_members() {
    let rt = Rt::new();
    let math = global(&rt, "Math");
    let mut fails = Vec::new();
    for (name, len) in LENGTHS {
        let f = rt.get_str(&math, name).expect("function");
        if rt.get_str(&f, "length").expect("length") != Value::Number(f64::from(*len)) {
            fails.push(format!("Math.{name}: length"));
        }
    }
    for (name, v) in CONSTANTS {
        match rt.get_str(&math, name).expect("constant") {
            Value::Number(n) if n.to_bits() == v.to_bits() => {}
            other => fails.push(format!("Math.{name} = {other:?}, V8 {v}")),
        }
        let o = math.as_object().expect("Math");
        let flags = rt.get_own_property(o, &PropKey::from_str(name)).expect("own").map(|p| p.flags());
        if flags != Some(Flags::NONE) {
            fails.push(format!("Math.{name} flags {flags:?}"));
        }
    }
    for name in ["random", "f16round"] {
        if !rt.get_str(&math, name).expect("get").is_undefined() {
            fails.push(format!("Math.{name} must be absent"));
        }
    }
    let tag = rt.get_v(&math, &PropKey::Sym(rt.well_known(WellKnown::ToStringTag))).expect("toStringTag");
    if tag != Value::str("Math") {
        fails.push(format!("Math[Symbol.toStringTag] = {tag:?}"));
    }
    let o = math.as_object().expect("Math");
    let tag_flags = rt.get_own_property(o, &PropKey::Sym(rt.well_known(WellKnown::ToStringTag))).expect("own").map(|p| p.flags());
    if tag_flags != Some(Flags::CONFIG) {
        fails.push(format!("Math[Symbol.toStringTag] flags {tag_flags:?}"));
    }
    let f = math_fn(&rt, "abs");
    if rt.get_own_property(f.as_object().expect("fn"), &PropKey::from_str("length")).expect("own").map(|p| p.flags()) != Some(Flags::CONFIG) {
        fails.push("Math.abs.length flags".to_string());
    }
    let object_tostring = rt.get_str(&Value::Object(rt.intrinsic(Intrinsic::ObjectPrototype)), "toString").expect("toString");
    let shown = rt.call(&object_tostring, &math, &[]).expect("toString");
    if shown != Value::str("[object Math]") {
        fails.push(format!("Object.prototype.toString.call(Math) = {shown:?}"));
    }
    assert!(fails.is_empty(), "Math shape differs:\n{}", fails.join("\n"));
}

#[test]
fn special_values_and_argument_order() {
    let rt = Rt::new();
    let mut fails = Vec::new();
    let as_text = |n: f64| number_to_string(n);
    let cases: &[(&str, &[f64], &str)] = &[
        ("imul", &[2147483648.0, 2.0], "0"),
        ("clz32", &[0.0], "32"),
        ("clz32", &[-1.0], "0"),
        ("fround", &[5e-46], "0"),
        ("fround", &[1.1], "1.100000023841858"),
        ("round", &[0.49999999999999994], "0"),
        ("round", &[4503599627370497.0], "4503599627370497"),
        ("sign", &[-0.0], "0"),
    ];
    for (name, args, want) in cases {
        let got = as_text(math_call(&rt, name, args));
        check(&format!("Math.{name}{args:?}"), &got, want, "", "", &mut fails);
    }
    if math_call(&rt, "round", &[-0.5]).to_bits() != (-0.0f64).to_bits() {
        fails.push("Math.round(-0.5) must be -0".to_string());
    }
    if math_call(&rt, "sign", &[-0.0]).to_bits() != (-0.0f64).to_bits() {
        fails.push("Math.sign(-0) must be -0".to_string());
    }
    if math_call(&rt, "max", &[-0.0, 0.0]).to_bits() != 0.0f64.to_bits() {
        fails.push("Math.max(-0, 0) must be +0".to_string());
    }
    if math_call(&rt, "hypot", &[-0.0, -0.0]).to_bits() != 0.0f64.to_bits() {
        fails.push("Math.hypot(-0, -0) must be +0".to_string());
    }
    check("Math.min()", &as_text(math_call(&rt, "min", &[])), "Infinity", "", "", &mut fails);
    check("Math.max()", &as_text(math_call(&rt, "max", &[])), "-Infinity", "", "", &mut fails);
    check("Math.hypot()", &as_text(math_call(&rt, "hypot", &[])), "0", "", "", &mut fails);
    check("Math.hypot(3, 4)", &as_text(math_call(&rt, "hypot", &[3.0, 4.0])), "5", "", "", &mut fails);
    check("Math.pow(NaN, 0)", &as_text(math_call(&rt, "pow", &[f64::NAN, 0.0])), "1", "", "", &mut fails);
    check("Math.pow(1, Infinity)", &as_text(math_call(&rt, "pow", &[1.0, f64::INFINITY])), "NaN", "", "", &mut fails);
    // Each argument is converted once, in order, before the function uses any of them.
    let t = |tag: &str, v: f64| tagged(&rt, tag, v);
    let r = rt.call(&math_fn(&rt, "atan2"), &Value::Undefined, &[t("y", 1.0), t("x", 2.0)]).expect("atan2");
    check("atan2 order", &show_num(&r), "0.4636476090008061", &take_log(), "y.valueOf,x.valueOf", &mut fails);
    let r = rt.call(&math_fn(&rt, "max"), &Value::Undefined, &[Value::Number(f64::NAN), t("a", 1.0), t("b", 2.0)]).expect("max");
    check("max with NaN first still converts all", &show_num(&r), "NaN", &take_log(), "a.valueOf,b.valueOf", &mut fails);
    let r = rt.call(&math_fn(&rt, "hypot"), &Value::Undefined, &[t("a", f64::NAN), t("b", f64::INFINITY)]).expect("hypot");
    check("hypot infinity beats NaN", &show_num(&r), "Infinity", &take_log(), "a.valueOf,b.valueOf", &mut fails);
    let r = rt.call(&math_fn(&rt, "imul"), &Value::Undefined, &[t("a", 1.0), t("b", 2.0)]).expect("imul");
    check("imul order", &show_num(&r), "2", &take_log(), "a.valueOf,b.valueOf", &mut fails);
    let r = rt.call(&math_fn(&rt, "clz32"), &Value::Undefined, &[t("a", 1.0)]).expect("clz32");
    check("clz32 one argument", &show_num(&r), "31", &take_log(), "a.valueOf", &mut fails);
    let sym = Value::Symbol(rt.new_symbol(None));
    let r = rt.call(&math_fn(&rt, "fround"), &Value::Undefined, &[sym]);
    check("fround of a symbol", &show(&rt, &r), "throw:TypeError", "", "", &mut fails);
    assert!(fails.is_empty(), "special values differ from V8:\n{}", fails.join("\n"));
}

fn show_num(v: &Value) -> String {
    match v {
        Value::Number(n) => number_to_string(*n),
        other => format!("{other:?}"),
    }
}

fn show(rt: &Rt, r: &Res<Value>) -> String {
    match r {
        Ok(v) => show_num(v),
        Err(vn_value::Throw(e)) => {
            let name = rt.get_str(e, "name").ok().and_then(|v| if let Value::String(s) = v { Some(s.to_rust_string_lossy()) } else { None });
            format!("throw:{}", name.unwrap_or_default())
        }
    }
}
