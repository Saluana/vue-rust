use vn_value::number::number_to_string;
use vn_value::{Call, Flags, Intrinsic, PropKey, Res, Rt, Value, WellKnown};

fn global(rt: &Rt, name: &str) -> Value {
    rt.get_str(&Value::Object(rt.intrinsic(Intrinsic::Global)), name).expect("global binding")
}

fn math_fn(rt: &Rt, name: &str) -> Value {
    rt.get_str(&global(rt, "Math"), name).expect("Math function")
}

/// Math.name(args) as a number. Panics on a throw: the table calls only number arguments.
fn math_call(rt: &Rt, name: &str, args: &[f64]) -> f64 {
    let f = math_fn(rt, name);
    let vals: Vec<Value> = args.iter().map(|x| Value::Number(*x)).collect();
    match rt.call(&f, &Value::Undefined, &vals) {
        Ok(Value::Number(n)) => n,
        other => panic!("Math.{name}({args:?}) returned {other:?}"),
    }
}

/// Position of a finite double on the ordered line of doubles (-0 and +0 are the same point).
fn ordered(x: f64) -> i64 {
    let b = x.to_bits() as i64;
    if b < 0 { i64::MIN - b } else { b }
}

fn ulp_distance(a: f64, b: f64) -> u64 {
    ordered(a).abs_diff(ordered(b))
}

fn same_bits(a: f64, b: f64) -> bool {
    (a.is_nan() && b.is_nan()) || a.to_bits() == b.to_bits()
}

